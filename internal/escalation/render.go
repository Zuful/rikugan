package escalation

import (
	"fmt"
	"slices"
	"sort"
	"strings"
	"time"

	"github.com/Zuful/rikugan/pkg/provider"
)

// Disclaimer ends every investigation message, whatever the agent said.
const Disclaimer = "Hypothesis generated by an LLM from untrusted data. Verify before acting."

// Unverified marks a quote rikugan did not find in the cited tool's
// output, or a tool the agent did not call.
const Unverified = "(unverified)"

// Meta is what rikugan measured of the investigation, not what the
// agent says of it.
type Meta struct {
	Duration time.Duration
	// Calls counts the agent's tool calls, by tool.
	Calls  map[string]int
	Tokens int
	// Cost in dollars; negative when the agent's server gave none.
	Cost float64
}

// Render writes the team message for a checked finding. Every free-text
// field goes through Clean; the action line, the tool counts and the
// disclaimer are rikugan's own.
func Render(c Checked, m Meta) provider.TeamMessage {
	var b strings.Builder
	fmt.Fprintf(&b, "Investigation (%s, %d tool calls, %s)\n", m.Duration.Round(time.Second), total(m.Calls), usage(m))
	fmt.Fprintf(&b, "Probable cause: %s\n", orNone(Clean(c.Cause, maxText)))
	if len(c.Evidence) > 0 {
		b.WriteString("Evidence:\n")
		for _, e := range c.Evidence {
			fmt.Fprintf(&b, "- [%s] %q", toolName(e.Tool), Clean(e.Quote, maxQuote))
			if note := Clean(e.Note, maxText); note != "" {
				fmt.Fprintf(&b, ": %s", note)
			}
			if !e.Verified {
				b.WriteString(" " + Unverified)
			}
			b.WriteString("\n")
		}
	}
	if len(c.RuledOut) > 0 {
		b.WriteString("Ruled out:\n")
		for _, r := range c.RuledOut {
			fmt.Fprintf(&b, "- %s: %s", Clean(r.Hypothesis, maxText), Clean(r.Reason, maxText))
			if r.Tool != "" {
				fmt.Fprintf(&b, " [%s]", toolName(r.Tool))
			}
			if !r.Verified {
				b.WriteString(" " + Unverified)
			}
			b.WriteString("\n")
		}
	}
	fmt.Fprintf(&b, "Suggested action: %s\n", actionLine(c))
	conf := string(c.Confidence)
	switch {
	case !c.Downgraded:
	case slices.ContainsFunc(c.Evidence, func(q CheckedQuote) bool { return q.Verified }):
		conf += " (high claimed, some evidence unverified)"
	default:
		conf += " (high claimed, no verified evidence)"
	}
	fmt.Fprintf(&b, "Confidence: %s\n", conf)
	fmt.Fprintf(&b, "Tools called: %s\n", toolCounts(m.Calls))
	b.WriteString(Disclaimer)
	return provider.TeamMessage{Severity: provider.SeverityInfo, Title: "Investigation", Body: b.String()}
}

func actionLine(c Checked) string {
	a := c.Action
	var s string
	switch a.Kind {
	case ActionRollback:
		s = fmt.Sprintf("roll %s back to revision %s", a.Service, a.Revision)
	case ActionRestart:
		s = "restart " + a.Service
	case ActionScale:
		s = "scale " + a.Service
	case ActionInspect:
		s = "inspect " + a.Target
	case ActionEscalate:
		s = "escalate"
		if a.Target != "" {
			s += " to " + a.Target
		}
	default:
		s = "none"
	}
	if c.ActionRejected {
		s += " (the proposed action named a target outside the incident and was rejected)"
	}
	return s
}

func usage(m Meta) string {
	s := fmt.Sprintf("%d tokens", m.Tokens)
	if m.Tokens >= 10000 {
		s = fmt.Sprintf("%dk tokens", (m.Tokens+500)/1000)
	}
	if m.Cost >= 0 {
		s += fmt.Sprintf(", $%.2f", m.Cost)
	}
	return s
}

func total(calls map[string]int) int {
	n := 0
	for _, c := range calls {
		n += c
	}
	return n
}

func toolCounts(calls map[string]int) string {
	if len(calls) == 0 {
		return "none"
	}
	names := make([]string, 0, len(calls))
	for n := range calls {
		names = append(names, n)
	}
	sort.Slice(names, func(i, j int) bool {
		if calls[names[i]] != calls[names[j]] {
			return calls[names[i]] > calls[names[j]]
		}
		return names[i] < names[j]
	})
	parts := make([]string, len(names))
	for i, n := range names {
		parts[i] = fmt.Sprintf("%s ×%d", n, calls[n])
	}
	return strings.Join(parts, ", ")
}

// toolName shows a tool name the agent wrote, cleaned: it is agent text.
func toolName(s string) string {
	if isTool(s) {
		return s
	}
	return "?"
}

func orNone(s string) string {
	if s == "" {
		return "none given"
	}
	return s
}
